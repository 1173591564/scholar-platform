def title_to_module_name(title: str) -> str:
    """Convert paper title to a Python-safe module name.
    
    "Attention Is All You Need" -> "attention_is_all_you_need"
    """
    if not title:
        return "untitled_model"
    cleaned = re.sub(r"[^a-zA-Z0-9\s]", "", title)
    return "_".join(w.lower() for w in cleaned.split()[:6]) if cleaned.strip() else "untitled_model"


