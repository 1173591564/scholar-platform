HYPERPARAM_PATTERNS = {
    "learning_rate": [
        r"learning\s+rate\s*(?:of|is|=|:)\s*([\d.e\-]+)",
        r"lr\s*=\s*([\d.e\-]+)",
        r"Adam.*?lr\s*=\s*([\d.e\-]+)",
    ],
    "batch_size": [
        r"batch\s+size\s*(?:of|is|=|:)\s*(\d+)",
        r"batch\s*=\s*(\d+)",
    ],
    "epochs": [
        r"(\d+)\s+epochs",
        r"train\s+for\s+(\d+)\s+epochs",
        r"epochs\s*=\s*(\d+)",
    ],
    "optimizer": [
        r"optimizer\s*(?:is|=|:)\s*(\w+)",
        r"using\s+(\w+)\s+optimizer",
        r"optimized\s+by\s+(\w+)",
    ],
    "weight_decay": [
        r"weight\s+decay\s*(?:of|is|=|:)\s*([\d.e\-]+)",
    ],
    "warmup_steps": [
        r"warmup\s+(?:steps|steps)\s*(?:of|is|=|:)\s*(\d+)",
    ],
}


def extract_hyperparameters(sections: list[dict]) -> dict:
    """Extract hyperparameters from paper sections text."""
    full_text = " ".join(
        s.get("content", "") + " " + s.get("heading", "")
        for s in sections
    )
    params = {}
    for key, patterns in HYPERPARAM_PATTERNS.items():
        for pattern in patterns:
            match = re.search(pattern, full_text, re.IGNORECASE)
            if match:
                try:
                    val = match.group(1)
                    if key in ("batch_size", "epochs", "warmup_steps"):
                        params[key] = int(val)
                    elif key == "optimizer":
                        params[key] = val
                    else:
                        params[key] = float(val)
                except (ValueError, IndexError):
                    pass
                break
    return params


