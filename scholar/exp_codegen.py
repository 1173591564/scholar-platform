def generate_experiment_template(paper_id: str, output_dir: Path = None) -> dict:
    """
    Generate experiment code template from paper JSON.
    
    Args:
        paper_id: Paper ID (ULID/arXiv/DOI/slug)
        output_dir: Output directory (default: config.EXPERIMENTS_DIR / <ULID>)
    
    Returns: {ulid, title, files_created, formulas_count, hyperparams}
    """
    from .id_resolver import resolve_id
    ulid = resolve_id(paper_id) or paper_id

    # Load paper data
    json_path = config.PARSED_DIR / f"{ulid}.json"
    if not json_path.exists():
        return {"error": f"Paper JSON not found: {json_path}"}

    data = json.loads(json_path.read_text(encoding="utf-8"))
    title = data.get("title", "Untitled")
    authors = data.get("authors", [])
    formulas = data.get("formulas", [])
    sections = data.get("sections", [])

    # Extract hyperparameters
    hyperparams = extract_hyperparameters(sections)

    # Create output directory
    if output_dir is None:
        output_dir = config.EXPERIMENTS_DIR / ulid
    output_dir.mkdir(parents=True, exist_ok=True)

    # Generate files
    files = {
        "model.py": generate_model_py(formulas, title),
        "data.py": generate_data_py(),
        "train.py": generate_train_py(formulas, title),
        "evaluate.py": generate_evaluate_py(),
        "config.yaml": generate_config_yaml(hyperparams, title),
        "requirements.txt": generate_requirements_txt(),
        "README.md": generate_readme_md(title, ulid, formulas, authors),
    }

    # Write files
    for filename, content in files.items():
        (output_dir / filename).write_text(content, encoding="utf-8")

    return {
        "ulid": ulid,
        "title": title,
        "files_created": list(files.keys()),
        "formulas_count": len(formulas),
        "hyperparams": hyperparams,
        "output_dir": str(output_dir),
    }
